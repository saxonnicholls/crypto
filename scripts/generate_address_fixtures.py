#!/usr/bin/env python3
#
#  generate_address_fixtures.py
#  snicholls-crypto
#
#  Copyright 2010-2026 Saxon Herschel Nicholls
#
#  Converts the address test vectors into the line-based fixtures under tests/fixtures/address/, which the tests read
#  at run time. The sources are downloaded by hand into a directory of their own and passed here; this script never
#  fetches anything, and refuses a source whose SHA-256 is not the one recorded below (and in
#  tests/fixtures/README.md).
#
#      python3 -I scripts/generate_address_fixtures.py --source DIR           write every fixture
#      python3 -I scripts/generate_address_fixtures.py --source DIR --check   compare, write nothing
#
#  Sources (DIR holds them under these names):
#    bip-0173.mediawiki         github.com/bitcoin/bips at a7f91321f25b5be8d93e901775621c21519e80b7 (BSD-2-Clause)
#    bip-0350.mediawiki         the same commit (BSD-2-Clause)
#    base58_encode_decode.json  github.com/bitcoin/bitcoin src/test/data/ at v28.0,
#                               110183746150428e6385880c79f8c5733b1361ba (MIT)
#
#  Fixtures:
#    address/bech32.txt   "variant valid|invalid <hex of the string>": the strings are hex because BIP-173's invalid
#                         list holds a space, DEL, 0x80 and 0xFF
#    address/segwit.txt   "bip173|bip350 valid|invalid <address> <scriptPubKey hex or ->", as each BIP lists them.
#                         BIP-350 supersedes BIP-173's valid list for versions 1 to 16 (those were bech32, now
#                         bech32m); the test applies BIP-350's rule to them.
#    address/base58.txt   "<hex bytes or -> <base58 text or ->"
#

import argparse
import hashlib
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "tests", "fixtures", "address")

SOURCES = {
    "bip-0173.mediawiki": "b19eab06b264bbd15ad7f7d640fa34de8f4a8809fba8a6ecc3e165545b27a543",
    "bip-0350.mediawiki": "63634b06aa8bae88b31929674736e74964c4598684269ac2b0b140c43a7a0dec",
    "base58_encode_decode.json": "73006fdb9d8337117bf330c1900974a1242f2e61fd6a1b77217328dbc4b72025",
}

HEADER = "# Generated by scripts/generate_address_fixtures.py from %s (SHA-256 %s); never edit by hand.\n"

ITEM = re.compile(r"^\* (?:(0x[0-9A-Fa-f]{2}) \+ )?<tt>([^<]*)</tt>(?: \+ (0x[0-9A-Fa-f]{2}))?(?:: <tt>([0-9a-f]*)</tt>)?")


def read(directory, name):
    data = open(os.path.join(directory, name), "rb").read()
    digest = hashlib.sha256(data).hexdigest()
    if digest != SOURCES[name]:
        sys.exit("generate_address_fixtures: %s has SHA-256 %s, expected %s" % (name, digest, SOURCES[name]))
    return data


def items(lines):
    """The (string, script) of each bullet: prefix and suffix bytes given as 0xNN are put back into the string."""
    out = []
    for line in lines:
        m = ITEM.match(line)
        if not m:
            continue
        text = m.group(2).encode("latin-1")
        if m.group(1):
            text = bytes([int(m.group(1), 16)]) + text
        if m.group(3):
            text = text + bytes([int(m.group(3), 16)])
        out.append((text, m.group(4)))
    return out


def sections(text, starts):
    """Split the BIP's lines at the first line containing each start marker, in order."""
    lines = text.splitlines()
    idx = []
    pos = 0
    for marker in starts:
        while marker not in lines[pos]:
            pos += 1
        idx.append(pos)
    idx.append(len(lines))
    return [lines[idx[i]:idx[i + 1]] for i in range(len(starts))]


def bip173(text):
    valid, invalid, seg_valid, seg_invalid = sections(text, [
        "The following strings are valid Bech32", "The following string are not valid Bech32",
        "valid segwit addresses and the scriptPubKey", "invalid segwit addresses and the reason"])
    seg_invalid = seg_invalid[:next(i for i, l in enumerate(seg_invalid) if l.startswith("===Checksum design"))]
    return valid, invalid, seg_valid, seg_invalid


def bip350(text):
    valid, invalid, seg_valid, seg_invalid = sections(text, [
        "The following strings are valid Bech32m", "The following string are not valid Bech32m",
        "valid segwit addresses and the scriptPubKey", "invalid segwit addresses and the reason"])
    seg_invalid = seg_invalid[:next(i for i, l in enumerate(seg_invalid) if l.startswith("==Appendix"))]
    return valid, invalid, seg_valid, seg_invalid


def build(directory):
    b173 = read(directory, "bip-0173.mediawiki").decode("utf-8")
    b350 = read(directory, "bip-0350.mediawiki").decode("utf-8")
    b58 = json.loads(read(directory, "base58_encode_decode.json"))

    files = {}
    lines = [HEADER % ("bip-0173.mediawiki and bip-0350.mediawiki", SOURCES["bip-0173.mediawiki"] + ", " + SOURCES["bip-0350.mediawiki"])]
    segwit = list(lines)
    for (variant, bip), parts in ((("bech32", "bip173"), bip173(b173)), (("bech32m", "bip350"), bip350(b350))):
        valid, invalid, seg_valid, seg_invalid = parts
        for s, _ in items(valid):
            lines.append("%s valid %s\n" % (variant, s.hex()))
        for s, _ in items(invalid):
            lines.append("%s invalid %s\n" % (variant, s.hex()))
        for s, script in items(seg_valid):
            segwit.append("%s valid %s %s\n" % (bip, s.decode("ascii"), script))
        for s, _ in items(seg_invalid):
            segwit.append("%s invalid %s -\n" % (bip, s.decode("ascii")))
    files["bech32.txt"] = "".join(lines)
    files["segwit.txt"] = "".join(segwit)

    rows = [HEADER % ("base58_encode_decode.json", SOURCES["base58_encode_decode.json"])]
    for hexbytes, text in b58:
        rows.append("%s %s\n" % (hexbytes or "-", text or "-"))
    files["base58.txt"] = "".join(rows)
    return files


def main():
    ap = argparse.ArgumentParser(description="Convert the address test vectors into tests/fixtures/address/")
    ap.add_argument("--source", required=True, help="the directory holding the downloaded sources")
    ap.add_argument("--check", action="store_true", help="compare with the committed fixtures, write nothing")
    args = ap.parse_args()
    files = build(args.source)
    bad = 0
    os.makedirs(OUT, exist_ok=True)
    for name, content in sorted(files.items()):
        path = os.path.join(OUT, name)
        if args.check:
            current = open(path, encoding="utf-8").read() if os.path.exists(path) else None
            if current != content:
                print("generate_address_fixtures: %s is out of date" % name, file=sys.stderr)
                bad += 1
        else:
            open(path, "w", encoding="utf-8").write(content)
            print("wrote tests/fixtures/address/%s (%d lines)" % (name, content.count("\n") - 1))
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
