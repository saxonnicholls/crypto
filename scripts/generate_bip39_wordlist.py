#!/usr/bin/env python3
#
#  generate_bip39_wordlist.py
#  snicholls-crypto
#
#  Copyright 2010-2026 Saxon Herschel Nicholls
#
#  Writes include/snicholls/crypto/bip39/wordlist.hpp from BIP-39's official English list, and
#  tests/fixtures/bip39/trezor_english.txt from Trezor's reference vectors, after checking each source file's
#  SHA-256 against the pinned value below. The sources are downloaded by hand into a directory of their own
#  (they are untrusted input until their hashes match) and passed with --source:
#
#      english.txt   https://github.com/bitcoin/bips/blob/a7f91321f25b5be8d93e901775621c21519e80b7/bip-0039/english.txt
#      vectors.json  https://github.com/trezor/python-mnemonic/blob/b57a5ad77a981e743f4167ab2f7927a55c1e82a8/vectors.json
#
#      python3 scripts/generate_bip39_wordlist.py --source DIR    regenerate both files
#      python3 scripts/generate_bip39_wordlist.py --check         offline: the committed header holds exactly the
#                                                                 official list (its SHA-256 recomputed from the
#                                                                 header's words), and the fixture names its source
#
#  Exit status is 0 on success and 1 on any mismatch.
#

import argparse
import hashlib
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HEADER = os.path.join(ROOT, "include", "snicholls", "crypto", "bip39", "wordlist.hpp")
FIXTURE = os.path.join(ROOT, "tests", "fixtures", "bip39", "trezor_english.txt")

ENGLISH_SHA256 = "2f5eed53a4727b4bf8880d8f3f199efc90e58503646d9ff8eff3a2ed3b24dbda"
VECTORS_SHA256 = "fa3b937b7cff9c9b8ecd3aa011faeb8d6dd67993174b72326e83f4de8fdb30f8"
BIPS_COMMIT = "a7f91321f25b5be8d93e901775621c21519e80b7"
TREZOR_COMMIT = "b57a5ad77a981e743f4167ab2f7927a55c1e82a8"

HEADER_TOP = """//
//  wordlist.hpp
//  snicholls-crypto
//
//  Copyright 2010-2026 Saxon Herschel Nicholls
//
//  GENERATED by scripts/generate_bip39_wordlist.py from BIP-39's english.txt
//  (bitcoin/bips at %(commit)s, SHA-256 %(sha)s). Do not edit by hand.
//  The word list is part of BIP-39, whose header states License: MIT.
//

/// \\file
/// \\brief `bip39::english`: BIP-39's English word list, 2048 words, as a compile-time table.
/// \\ingroup wallet
///
/// \\overview
/// The 2048 words a mnemonic is written in, sorted, each 3 to 8 lower-case ASCII letters, with the property BIP-39
/// relies on that the first four letters identify a word. `english` holds them as text; `english_packed` holds
/// each as one 64-bit integer (the letters little-endian, zero-padded), so that a word can be looked up by
/// comparing against every entry with masks (`find_word_ct`), in time that does not depend on the word.
///
/// Only the English list is included. BIP-39's other official lists are under the same licence, but French and
/// Spanish carry accents and Japanese uses an ideographic space, so their mnemonics and seeds need NFKD
/// normalisation, which this library does not have (see `bip39/mnemonic.hpp`); the rest would each add a table
/// to every compile for little use. The generator takes another list the same way if one is wanted.
///
/// \\relations
/// - `bip39/mnemonic.hpp`: entropy to words, words to entropy, the seed.
/// - Group: \\ref wallet.
///
/// \\impls
/// One table, generated.
///
/// \\contracts
/// - `constexpr` data; `find_word_ct` is `constexpr`, `noexcept`, and scans all 2048 entries whatever the word.
/// - The table is checked at compile time: sorted, unique, 3 to 8 letters, unique four-letter prefixes.
///
/// \\errors
/// None: a word that is not in the list is index 2048 from `find_word_ct`.
///
/// \\examples
/// \\snippet bip39/wordlist_demo.cpp wordlist
///
/// \\perf
/// Not benchmarked on its own: one lookup is 2048 compares, measured inside `benchmarks/bip39/mnemonic_benchmark.cpp`.
///
/// \\testing
/// `tests/bip39/wordlist_test.cpp`, `demos/bip39/wordlist_demo.cpp`; the CTest
/// `generated.bip39_wordlist_is_official` recomputes the official file's SHA-256 from this header.
///
/// \\deps
/// `<array>`, `<cstddef>`, `<cstdint>`, `<string_view>`.
///
/// \\gotchas
/// The table is about 24 KB of text and 16 KB of packed words in every program that uses it.
///
/// \\status
/// Stable data (BIP-39 is final); experimental API (0.1).

#ifndef snicholls_crypto_bip39_wordlist_hpp
#define snicholls_crypto_bip39_wordlist_hpp

#include <snicholls/crypto/constant_time.hpp>

#include <array>
#include <cstddef>
#include <cstdint>
#include <string_view>

/// \\brief BIP-39: mnemonic sentences and the seeds they give.
namespace snicholls::crypto::bip39 {

/// \\brief The number of words in a BIP-39 list.
inline constexpr std::size_t word_list_size = 2048;
/// \\brief The longest English word, in letters.
inline constexpr std::size_t max_word_length = 8;

/// \\brief BIP-39's English word list, in order: index i is the word for the 11-bit value i.
/// \\ingroup wallet
inline constexpr std::array<std::string_view, word_list_size> english = {
"""

HEADER_BOTTOM = """};

/// \\brief A word of at most eight letters as one integer: letter k in bits 8k to 8k + 7, the rest zero.
/// \\param w The word.
/// \\return The packed word, or 0 if it is empty or longer than eight letters.
[[nodiscard]] constexpr std::uint64_t pack_word(std::string_view w) noexcept
{
    if (w.empty() || w.size() > max_word_length)
        return 0;
    std::uint64_t v = 0;
    for (std::size_t k = 0; k < w.size(); ++k)
        v |= std::uint64_t{static_cast<unsigned char>(w[k])} << (8 * k);
    return v;
}

/// \\brief The English list packed by `pack_word`, built by the compiler.
/// \\ingroup wallet
inline constexpr std::array<std::uint64_t, word_list_size> english_packed = [] {
    std::array<std::uint64_t, word_list_size> t{};
    for (std::size_t i = 0; i < word_list_size; ++i)
        t[i] = pack_word(english[i]);
    return t;
}();

/// \\brief The index of a packed word, comparing against every entry: the time does not depend on the word.
/// \\param packed A word packed by `pack_word` (0 matches nothing).
/// \\return Its index, or `word_list_size` if it is not in the list.
[[nodiscard]] constexpr std::uint64_t find_word_ct(std::uint64_t packed) noexcept
{
    std::uint64_t index = word_list_size;
    for (std::uint64_t i = 0; i < word_list_size; ++i)
        index = ct::select(ct::mask_equal(english_packed[i], packed), i, index);
    return index;
}

namespace detail {
constexpr bool english_is_well_formed() noexcept
{
    for (std::size_t i = 0; i < word_list_size; ++i) {
        const auto w = english[i];
        if (w.size() < 3 || w.size() > max_word_length)
            return false;
        for (const char c : w)
            if (c < 'a' || c > 'z')
                return false;
        if (i > 0 && !(english[i - 1] < w))
            return false;
        if (i > 0 && english[i - 1].substr(0, 4) == w.substr(0, 4))
            return false;
    }
    return true;
}
} // namespace detail

static_assert(detail::english_is_well_formed(),
              "snicholls::crypto::bip39::english: the word list must be sorted, unique, 3 to 8 letters a-z, "
              "with unique four-letter prefixes");

} // namespace snicholls::crypto::bip39

#endif /* snicholls_crypto_bip39_wordlist_hpp */
"""


def sha256(data):
    return hashlib.sha256(data).hexdigest()


def generate(source):
    english = open(os.path.join(source, "english.txt"), "rb").read()
    if sha256(english) != ENGLISH_SHA256:
        sys.exit("generate_bip39_wordlist: english.txt does not have the pinned SHA-256")
    vectors = open(os.path.join(source, "vectors.json"), "rb").read()
    if sha256(vectors) != VECTORS_SHA256:
        sys.exit("generate_bip39_wordlist: vectors.json does not have the pinned SHA-256")

    words = english.decode("ascii").split("\n")
    assert words[-1] == "" and len(words) == 2049
    words = words[:-1]
    for w in words:
        assert re.fullmatch(r"[a-z]{3,8}", w), w

    lines = []
    for i in range(0, len(words), 8):
        lines.append("    " + " ".join('"%s",' % w for w in words[i:i + 8]))
    with open(HEADER, "w", encoding="utf-8", newline="\n") as f:
        f.write(HEADER_TOP % {"commit": BIPS_COMMIT, "sha": ENGLISH_SHA256})
        f.write("\n".join(lines) + "\n")
        f.write(HEADER_BOTTOM)

    rows = json.loads(vectors)["english"]
    with open(FIXTURE, "w", encoding="utf-8", newline="\n") as f:
        f.write("# Trezor's BIP-39 reference vectors, English, passphrase \"TREZOR\".\n")
        f.write("# Source: https://github.com/trezor/python-mnemonic/blob/%s/vectors.json\n" % TREZOR_COMMIT)
        f.write("# Source SHA-256: %s. Licence: MIT (python-mnemonic).\n" % VECTORS_SHA256)
        f.write("# Generated by scripts/generate_bip39_wordlist.py; do not edit by hand.\n")
        f.write("# Columns, separated by '|': entropy hex | mnemonic | seed hex | BIP-32 master xprv\n")
        for entropy, mnemonic, seed, xprv in rows:
            assert "|" not in mnemonic
            f.write("%s|%s|%s|%s\n" % (entropy, mnemonic, seed, xprv))
    print("wrote %s (%d words) and %s (%d vectors)" % (os.path.relpath(HEADER, ROOT), len(words),
                                                       os.path.relpath(FIXTURE, ROOT), len(rows)))


def check():
    text = open(HEADER, encoding="utf-8").read()
    body = text[text.index("english = {"):text.index("};")]
    words = re.findall(r'"([a-z]+)"', body)
    ok = True
    if len(words) != 2048 or sha256(("\n".join(words) + "\n").encode()) != ENGLISH_SHA256:
        print("generate_bip39_wordlist: the header's words are not BIP-39's english.txt", file=sys.stderr)
        ok = False
    fixture = open(FIXTURE, encoding="utf-8").read()
    if VECTORS_SHA256 not in fixture or TREZOR_COMMIT not in fixture:
        print("generate_bip39_wordlist: the fixture does not name its pinned source", file=sys.stderr)
        ok = False
    rows = [l for l in fixture.splitlines() if l and not l.startswith("#")]
    if len(rows) != 24:
        print("generate_bip39_wordlist: the fixture should hold Trezor's 24 English vectors", file=sys.stderr)
        ok = False
    if ok:
        print("bip39 word list: 2048 words, SHA-256 %s as published; fixture %d vectors" % (ENGLISH_SHA256, len(rows)))
    return 0 if ok else 1


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--source", help="directory holding english.txt and vectors.json")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    if a.check:
        return check()
    if not a.source:
        ap.error("--source DIR or --check")
    generate(a.source)
    return 0


if __name__ == "__main__":
    sys.exit(main())
